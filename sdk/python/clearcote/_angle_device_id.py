"""Add the PCI device id to an old capture's Windows WebGL renderer.

Captured profiles made on Chrome up to 117 carry a renderer with no device id:
    ANGLE (NVIDIA, NVIDIA GeForce RTX 4070 Ti Direct3D11 vs_5_0 ps_5_0, D3D11)
Chrome 118 and later always print "(0x%08X)" before "Direct3D11", so an engine on 156 showing the old
shape shows a string it cannot produce (the /audit row webgl-renderer-angle-format flags it). Same
rules as the Node and .NET SDKs and the Profile Manager; the table is generated by
sdk/scripts/gen_angle_device_ids.py.
"""

import json
import re

from ._angle_device_ids import BY_ARCH, BY_NAME

_NO_ID = re.compile(r"^ANGLE \(([^,]+), (.+?) (Direct3D11(?:on12)? vs_\d_\d ps_\d_\d, D3D11\))$")


def with_angle_device_id(renderer, arch=""):
    """The renderer with the device id ANGLE prints for that card; unchanged when it has one already,
    is not a Direct3D 11 renderer, or the card is not in the table. ``arch`` is the capture's WebGPU
    architecture: it picks an id of the same chip generation for a generic name."""
    if "(0x" in renderer:
        return renderer
    m = _NO_ID.match(renderer)
    if not m:
        return renderer
    vendor, name, tail = m.groups()
    dev = BY_ARCH.get(f"{vendor}|{name}|{arch}") or BY_NAME.get(f"{vendor}|{name}")
    return f"ANGLE ({vendor}, {name} ({dev}) {tail}" if dev else renderer


def fix_capture_renderers(capture):
    """Give every WebGL renderer in a parsed capture (a dict) its device id, in place. True when it changed."""
    webgl = capture.get("webgl") if isinstance(capture, dict) else None
    if not isinstance(webgl, dict):
        return False
    info = ((capture.get("webgpu") or {}).get("high_performance") or {}).get("info") or {}
    arch = info.get("architecture") if isinstance(info.get("architecture"), str) else ""
    changed = False
    for ctx in ("webgl1", "webgl2"):
        debug = (webgl.get(ctx) or {}).get("debug") if isinstance(webgl.get(ctx), dict) else None
        r = debug.get("UNMASKED_RENDERER_WEBGL") if isinstance(debug, dict) else None
        if not isinstance(r, str):
            continue
        fixed = with_angle_device_id(r, arch)
        if fixed != r:
            debug["UNMASKED_RENDERER_WEBGL"] = fixed
            changed = True
    return changed


def capture_for_engine(raw):
    """The capture's bytes as the engine should get them: renderers fixed, else the bytes as they were."""
    try:
        obj = json.loads(raw)
    except (ValueError, UnicodeDecodeError):
        return raw  # not JSON: handed over untouched, as before
    if isinstance(obj, dict) and fix_capture_renderers(obj):
        return json.dumps(obj, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    return raw
