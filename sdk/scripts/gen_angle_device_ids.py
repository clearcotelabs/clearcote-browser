"""Write the ANGLE device-id table for the three SDKs (Node, Python, .NET).

Captures made on Chrome up to 117 print a Windows WebGL renderer with no PCI device id:
    ANGLE (NVIDIA, NVIDIA GeForce RTX 4070 Ti Direct3D11 vs_5_0 ps_5_0, D3D11)
Chrome 118 and later print "(0x%08X)" before "Direct3D11", so an engine on 156 showing the old shape
shows a string it cannot produce. encodeProfile / encode_profile / EncodeProfile add the id from this
table before the capture goes to the engine.

The ids come from the captures in the chrome-fingerprints dataset that already print one, keyed by
vendor + name + the capture's WebGPU architecture (so a generic name such as "AMD Radeon(TM) Graphics"
gets an id of the capture's chip generation), then by vendor + name. Each key takes the id most
captures with it print; a tie goes to the lower id. Names the Profile Manager's GPU list
(src/lib/gpuModels.ts) knows and no capture names fill the name-only table. Same rules, same output
as the Profile Manager's scripts/gen-angle-device-ids.mjs.

Usage:
    python sdk/scripts/gen_angle_device_ids.py <device-library folder> [<path to PM src/lib/gpuModels.ts>]
The device-library folder is the one the Profile Manager builds (Device profiles -> full library):
index.json + profiles.bin.
"""

import gzip
import json
import os
import re
import sys
from collections import Counter, defaultdict

WITH_ID = re.compile(r"^ANGLE \(([^,]+), (.+?) \((0x[0-9A-F]{8})\) Direct3D11(?:on12)? vs_\d_\d ps_\d_\d, D3D11\)$")
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def build(lib_dir, models_path=None):
    with open(os.path.join(lib_dir, "index.json"), encoding="utf-8") as f:
        index = json.load(f)
    with open(os.path.join(lib_dir, "profiles.bin"), "rb") as f:
        blob = f.read()
    by_arch, by_name = defaultdict(Counter), defaultdict(Counter)
    for row in index["rows"]:
        m = WITH_ID.match(row.get("renderer") or "")
        if not m:
            continue
        off, ln = row["at"]
        d = json.loads(gzip.decompress(blob[off:off + ln]))
        arch = (((d.get("webgpu") or {}).get("high_performance") or {}).get("info") or {}).get("architecture") or ""
        by_arch[f"{m[1]}|{m[2]}|{arch}"][m[3]] += 1
        by_name[f"{m[1]}|{m[2]}"][m[3]] += 1
    from_models = 0
    if models_path:
        with open(models_path, encoding="utf-8") as f:
            for r in re.findall(r'renderer: "(ANGLE \([^"]+\))"', f.read()):
                w = WITH_ID.match(r)
                if not w or f"{w[1]}|{w[2]}" in by_name:
                    continue
                by_name[f"{w[1]}|{w[2]}"][w[3]] = 1
                from_models += 1
    pick = lambda c: sorted(c.items(), key=lambda kv: (-kv[1], kv[0]))[0][0]
    table = lambda m: {k: pick(m[k]) for k in sorted(m)}
    return index.get("commit", "?"), table(by_arch), table(by_name), from_models


def write(commit, by_arch, by_name):
    head = f"chrome-fingerprints captures (commit {commit}) and the Profile Manager's gpuModels.ts"
    js = lambda t: json.dumps(t, indent=2, ensure_ascii=False)
    files = {
        "sdk/node/src/angledeviceids.generated.ts": (
            f"// GENERATED by sdk/scripts/gen_angle_device_ids.py from the {head}. Do not edit by hand.\n\n"
            '/** "<vendor>|<name>|<WebGPU architecture>" -> the device id ANGLE prints, e.g. "0x00002782". */\n'
            f"export const BY_ARCH: Record<string, string> = {js(by_arch)};\n\n"
            '/** "<vendor>|<name>" -> the device id most captures with that name print. */\n'
            f"export const BY_NAME: Record<string, string> = {js(by_name)};\n"
        ),
        "sdk/python/clearcote/_angle_device_ids.py": (
            f'"""GENERATED by sdk/scripts/gen_angle_device_ids.py from the {head}. Do not edit by hand."""\n\n'
            '# "<vendor>|<name>|<WebGPU architecture>" -> the device id ANGLE prints, e.g. "0x00002782".\n'
            f"BY_ARCH = {js(by_arch)}\n\n"
            '# "<vendor>|<name>" -> the device id most captures with that name print.\n'
            f"BY_NAME = {js(by_name)}\n"
        ),
        "sdk/dotnet/src/Clearcote/AngleDeviceIds.g.cs": (
            f"// GENERATED by sdk/scripts/gen_angle_device_ids.py from the {head}. Do not edit by hand.\n"
            "using System.Collections.Generic;\n\nnamespace Clearcote;\n\ninternal static class AngleDeviceIds\n{\n"
            '    /// "<vendor>|<name>|<WebGPU architecture>" -> the device id ANGLE prints, e.g. "0x00002782".\n'
            "    internal static readonly IReadOnlyDictionary<string, string> ByArch = new Dictionary<string, string>\n    {\n"
            + "".join(f"        [{json.dumps(k, ensure_ascii=False)}] = {json.dumps(v)},\n" for k, v in by_arch.items())
            + "    };\n\n"
            '    /// "<vendor>|<name>" -> the device id most captures with that name print.\n'
            "    internal static readonly IReadOnlyDictionary<string, string> ByName = new Dictionary<string, string>\n    {\n"
            + "".join(f"        [{json.dumps(k, ensure_ascii=False)}] = {json.dumps(v)},\n" for k, v in by_name.items())
            + "    };\n}\n"
        ),
    }
    for rel, text in files.items():
        with open(os.path.join(ROOT, rel), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    commit, by_arch, by_name, from_models = build(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
    write(commit, by_arch, by_name)
    print(f"wrote {len(by_arch)} name+architecture keys, {len(by_name)} names ({from_models} from gpuModels.ts)")
